/**
 * Legal documents: `content/{locale}/{document}.md` → `libs/legal/content/src/generated/{document}.{locale}.ts`.
 *
 * - `title` and `updated` from the frontmatter, HTML from Markdown (GFM: tables, email autolinks → `mailto:`).
 * - `##` get ids from the English heading with the same index, so anchors are the same in every locale.
 * - Tables are wrapped to scroll horizontally on narrow screens instead of the page.
 * - A missing translation falls back to English (`fallback: true`); a `TODO:` line fails the build.
 *
 * Run through `nx run legal/content:content` (a dependency of the site build).
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

import matter from 'gray-matter';
import { Marked, Renderer } from 'marked';

const ROOT = join(import.meta.dirname, '../..');
const CONTENT = join(ROOT, 'content');
const OUT = join(ROOT, 'libs/legal/content/src/generated');
const DOCUMENTS = ['privacy', 'terms', 'consent'];
const LOCALES = ['en', 'ru', 'es'];
const SOURCE_LOCALE = 'en';

function slug(text) {
  return text
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function read(document, locale) {
  const file = join(CONTENT, locale, `${document}.md`);
  if (!existsSync(file)) {
    return null;
  }

  const { data, content } = matter(readFileSync(file, 'utf8'));
  if (!data.title || !data.updated) {
    throw new Error(`${file}: frontmatter needs "title" and "updated"`);
  }
  if (/^\s*TODO:/m.test(content)) {
    throw new Error(`${file}: contains a TODO line, the document is not ready`);
  }

  const updated = data.updated instanceof Date ? data.updated.toISOString().slice(0, 10) : String(data.updated);
  return { file, title: String(data.title), updated, markdown: content };
}

function decode(text) {
  return text.replace(/&(#39|quot|lt|gt|amp);/g, (_, entity) => ({ '#39': "'", quot: '"', lt: '<', gt: '>', amp: '&' })[entity]);
}

function h2Texts(markdown) {
  return new Marked()
    .lexer(markdown)
    .filter((token) => token.type === 'heading' && token.depth === 2)
    .map((token) => token.text);
}

function render(markdown, ids) {
  const toc = [];
  let index = 0;
  const marked = new Marked({ gfm: true });
  marked.use({
    renderer: {
      heading(token) {
        if (token.depth !== 2) {
          return false;
        }
        const id = ids[index++];
        const text = this.parser.parseInline(token.tokens);
        toc.push({ id, title: decode(text.replace(/<[^>]+>/g, '')) });
        return `<h2 id="${id}">${text}</h2>\n`;
      },
      table(token) {
        // Focusable: a region that scrolls horizontally must be reachable from the keyboard (axe scrollable-region-focusable).
        return `<div class="overflow-x-auto" tabindex="0">${Renderer.prototype.table.call(this, token)}</div>\n`;
      },
    },
  });

  return { html: marked.parse(markdown), toc };
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

for (const document of DOCUMENTS) {
  const source = read(document, SOURCE_LOCALE);
  if (!source) {
    throw new Error(`content/${SOURCE_LOCALE}/${document}.md is required`);
  }
  const ids = h2Texts(source.markdown).map(slug);

  for (const locale of LOCALES) {
    const translation = read(document, locale);
    const doc = translation ?? source;
    const headings = h2Texts(doc.markdown);
    if (headings.length !== ids.length) {
      throw new Error(`${doc.file}: ${headings.length} "##" sections, the English version has ${ids.length} — anchors must match`);
    }

    const { html, toc } = render(doc.markdown, ids);
    const module = { title: doc.title, updated: doc.updated, fallback: !translation, toc, html };
    writeFileSync(
      join(OUT, `${document}.${locale}.ts`),
      `// Generated by tools/scripts/content.mjs from content/${translation ? locale : SOURCE_LOCALE}/${document}.md. Do not edit.\n` +
        `import { LegalDocument } from '../lib/legal-document';\n\n` +
        `const document: LegalDocument = ${JSON.stringify(module, null, 2)};\n\nexport default document;\n`,
    );
  }
}

console.log(`content: ${DOCUMENTS.length * LOCALES.length} documents → ${OUT.replace(ROOT + '/', '')}`);
